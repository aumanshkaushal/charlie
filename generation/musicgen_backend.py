"""Optional pretrained MusicGen Small backend integration for Charlie."""
import os
import torch
import numpy as np


class MusicGenBackend:
    """
    Wrapper for facebook/musicgen-small.
    Accepts text condition generated by Charlie's adapter and synthesizes neural audio.
    """
    def __init__(
        self,
        model_path: str = "models/musicgen-small",
        device: str = "cuda" if torch.cuda.is_available() else "cpu",
        torch_dtype: torch.dtype = torch.float16,
    ):
        self.model_path = model_path
        self.device = device
        self.torch_dtype = torch_dtype if device == "cuda" else torch.float32
        self.model = None
        self.processor = None
        self._is_available = os.path.exists(model_path)

    @property
    def is_available(self) -> bool:
        return self._is_available

    def load_model(self):
        """Lazy load to prevent holding GPU VRAM when not in use."""
        if self.model is not None:
            return

        if not self._is_available:
            raise FileNotFoundError(f"MusicGen Small not found at {self.model_path}")

        print(f"Loading MusicGen Small from {self.model_path} into {self.device} ({self.torch_dtype})...")
        from transformers import AutoProcessor, MusicgenForConditionalGeneration

        self.processor = AutoProcessor.from_pretrained(self.model_path)
        self.model = MusicgenForConditionalGeneration.from_pretrained(
            self.model_path,
            torch_dtype=self.torch_dtype,
        ).to(self.device)
        self.model.eval()
        print("MusicGen Small loaded successfully.")

    def generate(
        self,
        prompt: str,
        duration_tokens: int = 256,  # ~5 seconds of audio
        guidance_scale: float = 3.0,
    ) -> tuple[np.ndarray, int]:
        """
        Generate audio from prompt text.
        Returns: (audio_waveform, sample_rate)
        """
        self.load_model()

        inputs = self.processor(
            text=[prompt],
            padding=True,
            return_tensors="pt",
        ).to(self.device)

        with torch.no_grad():
            audio_values = self.model.generate(
                **inputs,
                max_new_tokens=duration_tokens,
                guidance_scale=guidance_scale,
                do_sample=True,
            )

        # Convert to numpy [num_samples]
        waveform = audio_values[0, 0].cpu().float().numpy()
        sample_rate = self.model.config.audio_encoder.sampling_rate

        return waveform, sample_rate

    def unload(self):
        """Free GPU VRAM."""
        if self.model is not None:
            del self.model
            del self.processor
            self.model = None
            self.processor = None
            if torch.cuda.is_available():
                torch.cuda.empty_cache()
            print("MusicGen Small unloaded from memory.")
